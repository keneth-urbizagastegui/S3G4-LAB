# -*- coding: utf-8 -*-
"""Redibujos propios (simplificados) del WAVE2: grueso sin rele (placa 105-15801-00E) y salida del generador (105-15800-00J)."""
from sch import Sch

def rev_e():
    s = Sch(1300, 560, "WAVE2 rev E - dos divisores bufferizados y conmutacion en baja impedancia")
    y = 190
    p = s.bnc(50, y, "J1", "BNC")
    s.wire(p, (110, y)); s.dot(110, y)
    s.C((110, y), (230, y), "C1", "0.1 µF 100 V", side="b")
    B = s.box(130, 80, 80, 40, "RLY1 · CPC1017N", "", pins=(("l", 20, "", "l"), ("r", 20, "", "r")))
    s.text(170, 105, "PhotoMOS", "pin", "middle")
    s.wire((110, y), (110, 100), B["l"]); s.wire(B["r"], (230, 100), (230, y))
    s.dot(230, y); s.wire((230, y), (280, y)); s.dot(280, y)
    # rama A: /7.67 y x7.67
    s.wire((280, y), (280, 110))
    s.R((280, 110), (400, 110), "R1", "1.8 MΩ")
    s.wire((280, 110), (280, 60)); s.wire((400, 110), (400, 60))
    s.C((280, 60), (400, 60), "C2", "3 pF")
    s.dot(280, 110); s.dot(400, 110)
    s.wire((400, 110), (520, 110))
    s.dot(440, 110); s.R((440, 110), (440, 200), "R2", "270 kΩ", side="l"); s.gnd(440, 200)
    s.dot(490, 110); s.C((490, 110), (490, 200), "C3", "25 pF aj.", side="r", trim=True); s.gnd(490, 200)
    A = s.opamp(600, 126, "U1D", "×7.67", inp_top=True)
    s.wire((520, 110), A["inp"])
    s.wire(A["inm"], (580, 142), (580, 210)); s.dot(580, 210)
    s.R((580, 210), (700, 210), "R35", "1 kΩ", side="b")
    s.R((580, 210), (580, 280), "R36", "150 Ω", side="l"); s.gnd(580, 280)
    s.wire(A["out"], (740, 126)); s.dot(700, 126); s.wire((700, 210), (700, 126)); s.net(704, 126, "V11 (×1)")
    # rama B: /101 y seguidor
    s.wire((280, y), (280, 370))
    s.R((280, 370), (400, 370), "R3", "2.0 MΩ")
    s.wire((280, 370), (280, 430)); s.wire((400, 370), (400, 430))
    s.C((280, 430), (400, 430), "C5", "6 pF aj.", side="b", trim=True)
    s.dot(280, 370); s.dot(400, 370)
    s.wire((400, 370), (520, 370))
    s.dot(460, 370); s.R((460, 370), (460, 480), "R4", "20 kΩ", side="l"); s.gnd(460, 480)
    s.dot(510, 370); s.C((510, 370), (510, 480), "C6", "510 pF", side="r"); s.gnd(510, 480)
    Bf = s.opamp(600, 386, "U1C", "×1", inp_top=True)
    s.wire((520, 370), Bf["inp"])
    s.wire(Bf["inm"], (580, 402), (580, 440), (690, 440), (690, 386)); s.dot(690, 386)
    s.wire(Bf["out"], (740, 386)); s.net(694, 386, "V12 (÷101)")
    # 74HC4053
    U = s.box(790, 200, 120, 130, "U3 · 74HC4053 (2 canales)", "",
              pins=(("l", 30, "Y0", "y0"), ("l", 100, "Y1", "y1"), ("r", 60, "Y", "y"), ("b", 60, "B", "b")))
    s.wire((740, 126), (760, 126), (760, 230), U["y0"])
    s.wire((740, 386), (760, 386), (760, 300), U["y1"])
    s.wire(U["b"], (850, 360)); s.text(850, 376, "CH1SSEL3", "pin", "middle")
    s.wire(U["y"], (980, 260))
    s.port(980, 260, "U1A ×2 → escalera 1…1/40 → 4051 → ×8", "r")
    s.note(20, 520, "Zin = 2.07 MΩ ∥ 2.02 MΩ ≈ 1.02 MΩ: las dos ramas están siempre conectadas; ninguna ve más de microamperios. El 4053 conmuta salidas de amplificador,", "start")
    s.note(20, 538, "de baja impedancia: su capacidad en abierto no importa. Rama A: ÷7.67 y ×7.67 = ×1 neto; su entrada nunca ve la tensión completa de la BNC.", "start")
    return s.svg()

def generador():
    s = Sch(1300, 330, "WAVE2 - salida del generador, un canal")
    y = 150
    s.port(20, y, "DAC · PA4 del STM32F100", "r")
    s.wire((190, y), (240, y))
    s.R((240, y), (340, y), "R73", "470 Ω")
    s.dot(380, y); s.wire((340, y), (440, y))
    s.C((380, y), (380, 240), "C34", "20 nF", side="l")
    s.port(380, 256, "LFA · GPIO", "r")
    A = s.opamp(480, 166, "U17A", "TL082", inp_top=True)
    s.wire((440, y), A["inp"])
    s.wire(A["inm"], (460, 182), (460, 240)); s.dot(460, 240)
    s.R((460, 240), (600, 240), "R68", "10 kΩ", side="b")
    s.R((460, 240), (460, 300), "R67", "10 kΩ", side="r"); s.port(460, 308, "TSIGA_R · GPIO (offset)", "r")
    s.wire(A["out"], (640, 166)); s.dot(600, 166); s.wire((600, 240), (600, 166))
    s.R((640, 166), (760, 166), "R74", "100 Ω")
    s.port(760, 166, "TSIGA (salida)", "r")
    s.note(1290, 60, "LFA a nivel bajo: C34 conecta y forma con R73 un filtro de 16.9 kHz.", "end")
    s.note(1290, 78, "LFA en alta impedancia: el filtro desaparece. Un GPIO hace de interruptor.", "end")
    s.note(1290, 110, "Ganancia ×2. TSIGA_R a 0 V: sin offset; a 3.3 V: resta 3.3 V a la salida.", "end")
    s.note(1290, 128, "Por eso el protocolo sólo admite offset de 0 o 3.3 V.", "end")
    s.note(1290, 160, "R74 protege la salida contra cortocircuitos breves.", "end")
    return s.svg()
